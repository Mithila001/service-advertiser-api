CREATE TABLE business_moderation_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id INTEGER NOT NULL REFERENCES business (id) ON DELETE CASCADE,
    admin_id BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    action VARCHAR(20) NOT NULL CHECK (action IN ('SUSPENDED', 'ACTIVATED')),
    reason VARCHAR(500),
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX business_moderation_history_business_idx
    ON business_moderation_history (business_id, created_at DESC, id DESC);
