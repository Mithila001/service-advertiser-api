CREATE TABLE items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id INTEGER NOT NULL REFERENCES business (id) ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL CHECK (btrim(title) <> ''),
    description TEXT,
    type VARCHAR(20) NOT NULL CHECK (type IN ('PRODUCT', 'SERVICE')),
    price NUMERIC(19, 2) CHECK (price >= 0),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'INACTIVE')),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);
CREATE INDEX items_business_status_id_idx ON items (business_id, status, id);
